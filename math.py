# ceil = sempre ira arredondar para cima
print(math.ceil(5.1))

# floor = sempre ira arredondar para baixo
print(math.floor(5.9))

#fabs = valor absoluto
print(math.fabs(-8))

#fmod = retorna o resto da divisão entre dois números
print(math.fmod(5,2))

#sqrt = retorna a raiz quadrada de um número
print(math.sqrt(25))

#round = arredonda um número para o inteiro mais próximo
print(round(5.44,1))
